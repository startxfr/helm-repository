#!/usr/bin/env bash
# Refresh the files charts/unifai copies from the UnifAI operator sources, for one release tag :
#   - crds/*.yaml             <- fork/unifai-operator/config/crd/bases/
#   - files/manager-rules.yaml <- rules of the ClusterRole in fork/unifai-operator/config/rbac/role.yaml
# and print the image digests of that release (release.json) to report in values.yaml and Chart.yaml.
#
#   .tools/sync-unifai-operator.sh v0.1.71
set -euo pipefail

tag="${1:?usage: $0 <release tag, e.g. v0.1.71>}"
repo="startxfr/UnifAI"
root="$(cd "$(dirname "$0")/.." && pwd)"
chart="${root}/charts/unifai"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

curl -fsSL "https://codeload.github.com/${repo}/tar.gz/refs/tags/${tag}" | tar xz -C "$work"
src="$(echo "$work"/*/fork/unifai-operator)"
[ -d "$src/config/crd/bases" ] || { echo "no operator sources in ${repo}@${tag}" >&2; exit 1; }

rm -f "$chart"/crds/*.yaml
cp "$src"/config/crd/bases/*.yaml "$chart/crds/"
echo "copied $(ls "$chart/crds" | wc -l) CRDs"

# Rules of the first document (the ClusterRole) only ; the namespaced Role that follows is templated by hand.
{
  echo "# Rules of the operator ClusterRole, copied from ${repo}@${tag} (fork/unifai-operator/config/rbac/role.yaml)."
  echo "# Generated by .tools/sync-unifai-operator.sh : do not edit."
  awk '/^---$/ { if (seen) exit; next } /^rules:/ { seen = 1; next } seen' "$src/config/rbac/role.yaml"
} > "$chart/files/manager-rules.yaml"
echo "wrote files/manager-rules.yaml ($(grep -c -- '- apiGroups:' "$chart/files/manager-rules.yaml") rules)"

echo
echo "Image references of ${tag} (report them in charts/unifai/values.yaml and Chart.yaml) :"
curl -fsSL "https://github.com/${repo}/releases/download/${tag}/release.json" |
  python3 -I -c 'import json,sys; [print("  %-11s %s" % (k, v["ref"])) for k, v in json.load(sys.stdin)["images"].items()]'
echo
echo "Then compare the operator Deployment and RBAC with charts/unifai/templates/operator-*.yaml :"
echo "  fork/unifai-operator/config/manager/manager.yaml, config/rbac/, config/default/"
